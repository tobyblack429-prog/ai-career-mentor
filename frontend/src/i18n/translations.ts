export type DynamicTranslationKind = "skill" | "description" | "role" | "filename";

function containsChinese(value: string): boolean {
  return /[\u3400-\u9fff]/.test(value);
}

function translatePatternPart(value: string): string {
  const trimmed = value.trim();
  if (containsChinese(trimmed) || technicalTerms.has(trimmed)) return trimmed;
  return zhTranslations[trimmed] ?? "相关技能";
}

function translateKnownValue(value: string): string | undefined {
  const direct = zhTranslations[value];
  if (direct) return direct;

  for (const [pattern, replacer] of patternTranslations) {
    const match = value.match(pattern);
    if (match) return replacer(...match.slice(1));
  }

  return undefined;
}

/** Translate data restored from the API without ever exposing an unknown
 * English sentence in Chinese mode. The original data object is untouched. */
export function translateDynamicToChinese(value: string, kind: DynamicTranslationKind): string {
  const trimmed = value.trim();
  if (!trimmed) return "";
  if (containsChinese(trimmed)) return trimmed;
  const known = translateKnownValue(trimmed);
  if (known) return known;
  if (kind === "filename") return "当前简历文件";
  if (kind === "skill" && technicalTerms.has(trimmed)) return trimmed;
  if (kind === "role") return "其他职位";
  if (kind === "skill") return "其他相关技能";
  return "其他相关说明";
}

export function translateToChinese(value: string): string {
  // This function is also used by the DOM observer. Unknown static text must
  // remain untouched so React content, usernames, numbers, and file metadata
  // are not replaced globally; dynamic resume fields use the safe helper above.
  return translateKnownValue(value) ?? value;
}
